import {
  Check, ChevronDown, CircleCheck, Code2, FileVideo, ImagePlus, Link2, ListChecks,
  Loader2, Sparkles, TriangleAlert, Trash2, Upload, UploadCloud, X,
} from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { Btn, Card, Field, PageHeader, Select, TextArea } from "../portal/ui";
import { cn } from "../utils/cn";
import type { AdminVideo, CategoryRec } from "./data";

export type UploadSource = "file" | "iframe" | "link";

/** One queued item — each carries its own thumbnail and metadata. */
export interface QueueItem {
  id: string;
  source: UploadSource;
  sourceLabel: string;
  /** file | iframe | link progress of the simulated ingest. */
  phase: "uploading" | "probing" | "ready";
  progress: number;
  title: string;
  description: string;
  category: string;
  tags: string;
  /** Auto-generated by the simulated probe — read-only in the UI. */
  duration: string;
  quality: AdminVideo["quality"];
  thumb: string;
  thumbName: string;
  expanded: boolean;
}

export interface UploadPayload {
  source: UploadSource;
  sourceLabel: string;
  title: string;
  description: string;
  category: string;
  tags: string[];
  duration: string;
  quality: AdminVideo["quality"];
  thumb: string;
  publish: boolean;
}

interface UploadViewProps {
  categories: CategoryRec[];
  onPublish: (payloads: UploadPayload[]) => void;
}

const TABS: { key: UploadSource; label: string; icon: typeof Upload; hint: string }[] = [
  { key: "file", label: "Upload Videos", icon: UploadCloud, hint: "Select one or many files" },
  { key: "iframe", label: "Embed iFrames", icon: Code2, hint: "Paste embed snippets" },
  { key: "link", label: "Upload by Links", icon: Link2, hint: "Import from direct URLs" },
];

const fmtSize = (bytes: number) =>
  bytes > 1e9 ? `${(bytes / 1e9).toFixed(2)} GB` : `${(bytes / 1e6).toFixed(1)} MB`;

const titleFromName = (name: string) =>
  name.replace(/\.[^.]+$/, "").replace(/[-_]+/g, " ").replace(/\s+/g, " ").trim();

const titleFromUrl = (url: string) => {
  try {
    const last = new URL(url).pathname.split("/").filter(Boolean).pop() ?? "Imported video";
    return titleFromName(decodeURIComponent(last)) || "Imported video";
  } catch {
    return "Imported video";
  }
};

/** Pull every src="..." out of pasted iframe snippets (bare URLs also accepted). */
function extractSources(raw: string): string[] {
  const out: string[] = [];
  const re = /src\s*=\s*["']([^"']+)["']/gi;
  let m: RegExpExecArray | null;
  while ((m = re.exec(raw))) out.push(m[1]);
  if (out.length === 0) {
    raw
      .split(/[\s,]+/)
      .filter((s) => /^https?:\/\/\S+$/i.test(s.trim()))
      .forEach((s) => out.push(s.trim()));
  }
  return out;
}

/**
 * Deterministic pseudo-probe: derives a plausible duration and quality from the
 * source string so the operator does not have to type them. In a real system
 * these come from the transcoder; here they are generated locally.
 */
function probeMedia(seed: string): { duration: string; quality: AdminVideo["quality"] } {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  const mins = 8 + (h % 26);
  const secs = h % 60;
  return {
    duration: `${mins}:${String(secs).padStart(2, "0")}`,
    quality: h % 3 === 0 ? "4K" : "HD",
  };
}

/**
 * Admin → Upload (bulk).
 *
 * All three sources are FRONTEND SIMULATIONS. Files never leave the browser,
 * links are never fetched, and embeds are not rendered from remote origins.
 * Progress bars and the "probing" phase are timers that mimic a real pipeline.
 */
export default function UploadView({ categories, onPublish }: UploadViewProps) {
  const [tab, setTab] = useState<UploadSource>("file");
  const [queue, setQueue] = useState<QueueItem[]>([]);
  const [bulkText, setBulkText] = useState("");
  const [error, setError] = useState("");
  const [done, setDone] = useState<null | { count: number; published: boolean }>(null);

  /** Defaults applied to every new item and re-appliable to the whole queue. */
  const defaultCategory = categories[0]?.label ?? "Mature";
  const [applyCategory, setApplyCategory] = useState(defaultCategory);
  const [applyTags, setApplyTags] = useState("");

  const fileRef = useRef<HTMLInputElement>(null);
  const thumbRefs = useRef<Record<string, HTMLInputElement | null>>({});
  const timers = useRef<number[]>([]);

  useEffect(() => () => timers.current.forEach((t) => window.clearInterval(t)), []);

  const patch = (id: string, next: Partial<QueueItem>) =>
    setQueue((q) => q.map((it) => (it.id === id ? { ...it, ...next } : it)));

  /** Drive one item from uploading → probing → ready. */
  const runIngest = (id: string, seed: string, instant: boolean) => {
    if (instant) {
      patch(id, { phase: "probing", progress: 100 });
      const t = window.setTimeout(() => {
        patch(id, { phase: "ready", ...probeMedia(seed) });
      }, 700);
      timers.current.push(t);
      return;
    }
    const interval = window.setInterval(() => {
      setQueue((q) =>
        q.map((it) => {
          if (it.id !== id) return it;
          if (it.progress >= 100) return it;
          const progress = Math.min(100, it.progress + 4);
          if (progress === 100) {
            window.clearInterval(interval);
            const t = window.setTimeout(() => {
              patch(id, { phase: "ready", ...probeMedia(seed) });
            }, 700);
            timers.current.push(t);
            return { ...it, progress, phase: "probing" };
          }
          return { ...it, progress };
        })
      );
    }, 70);
    timers.current.push(interval);
  };

  const makeItem = (
    source: UploadSource,
    sourceLabel: string,
    title: string
  ): QueueItem => ({
    id: `q-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    source,
    sourceLabel,
    phase: "uploading",
    progress: 0,
    title,
    description: "",
    category: applyCategory,
    tags: applyTags,
    duration: "—",
    quality: "HD",
    thumb: "",
    thumbName: "",
    expanded: false,
  });

  /* ------------------------------ adders ------------------------------ */

  const addFiles = (files: FileList | null) => {
    if (!files?.length) return;
    const accepted = Array.from(files).filter((f) => f.type.startsWith("video/"));
    const rejected = files.length - accepted.length;
    setError(rejected > 0 ? `${rejected} file(s) skipped — only video/* is accepted.` : "");
    const items = accepted.map((f) =>
      makeItem("file", `${f.name} (${fmtSize(f.size)})`, titleFromName(f.name))
    );
    setQueue((q) => [...q, ...items]);
    items.forEach((it) => runIngest(it.id, it.sourceLabel, false));
    if (fileRef.current) fileRef.current.value = "";
  };

  const addBulkText = () => {
    const sources =
      tab === "iframe"
        ? extractSources(bulkText)
        : bulkText
            .split(/[\s,]+/)
            .map((s) => s.trim())
            .filter((s) => /^https?:\/\/.+\..+/.test(s));

    if (sources.length === 0) {
      setError(
        tab === "iframe"
          ? "No src attributes found — paste one or more iframe snippets."
          : "No valid URLs found — paste one or more https:// links."
      );
      return;
    }
    setError("");
    const items = sources.map((s) => makeItem(tab, s, titleFromUrl(s)));
    setQueue((q) => [...q, ...items]);
    items.forEach((it) => runIngest(it.id, it.sourceLabel, true));
    setBulkText("");
  };

  const pickThumb = (id: string, f: File | undefined) => {
    if (!f || !f.type.startsWith("image/")) return;
    patch(id, { thumb: URL.createObjectURL(f), thumbName: f.name });
  };

  /* ------------------------------ submit ------------------------------ */

  const readyCount = queue.filter((q) => q.phase === "ready").length;
  const allReady = queue.length > 0 && readyCount === queue.length;
  const untitled = queue.filter((q) => q.title.trim().length < 3).length;

  const submit = (publish: boolean) => {
    if (queue.length === 0) {
      setError("Add at least one video to the queue.");
      return;
    }
    if (!allReady) {
      setError("Wait for every item to finish processing.");
      return;
    }
    if (untitled > 0) {
      setError(`${untitled} item(s) need a title of at least 3 characters.`);
      return;
    }
    setError("");
    onPublish(
      queue.map((it) => ({
        source: it.source,
        sourceLabel: it.sourceLabel,
        title: it.title.trim(),
        description: it.description.trim(),
        category: it.category,
        tags: it.tags.split(",").map((t) => t.trim()).filter(Boolean),
        duration: it.duration,
        quality: it.quality,
        thumb: it.thumb,
        publish,
      }))
    );
    setDone({ count: queue.length, published: publish });
    setQueue([]);
  };

  /* ------------------------------ success ------------------------------ */

  if (done) {
    return (
      <div>
        <PageHeader title="Upload" sub="Add new content to the Erobabe library." />
        <Card className="mx-auto mt-10 max-w-md p-8 text-center">
          <span className="mx-auto flex h-12 w-12 items-center justify-center rounded-full border border-emerald-500/30 bg-emerald-500/10">
            <CircleCheck className="h-6 w-6 text-emerald-400" aria-hidden />
          </span>
          <h2 className="mt-3 text-[16px] font-semibold text-ink">
            {done.count} video{done.count === 1 ? "" : "s"}{" "}
            {done.published ? "added to the library" : "saved as drafts"}
          </h2>
          <p className="mt-1.5 text-[12px] leading-relaxed text-ink-3">
            Records were created in local state. This is a demo — nothing was uploaded and no
            remote service was contacted.
          </p>
          <Btn className="mt-4 w-full" onClick={() => setDone(null)}>
            Upload more
          </Btn>
        </Card>
      </div>
    );
  }

  /* -------------------------------- form -------------------------------- */

  return (
    <div>
      <PageHeader
        title="Upload"
        sub="Add videos in bulk by file, embed code or link — then edit each one below."
      />

      {/* source tabs */}
      <div className="mt-4 grid gap-2.5 sm:grid-cols-3">
        {TABS.map((t) => {
          const Icon = t.icon;
          const active = tab === t.key;
          return (
            <button
              key={t.key}
              type="button"
              onClick={() => {
                setTab(t.key);
                setError("");
                setBulkText("");
              }}
              aria-pressed={active}
              className={cn(
                "flex items-center gap-3 rounded-xl border p-3.5 text-left transition-colors",
                active
                  ? "border-accent/55 bg-accent/[0.07]"
                  : "border-line bg-pcard hover:border-zinc-600"
              )}
            >
              <span
                className={cn(
                  "flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border",
                  active
                    ? "border-accent/40 bg-accent/15 text-accent"
                    : "border-line bg-pcard-2 text-ink-3"
                )}
              >
                <Icon className="h-4 w-4" aria-hidden />
              </span>
              <span className="min-w-0">
                <span className={cn("block text-[12.5px] font-semibold", active ? "text-ink" : "text-ink-2")}>
                  {t.label}
                </span>
                <span className="block truncate text-[10.5px] text-ink-3">{t.hint}</span>
              </span>
              {active && (
                <span className="ml-auto flex h-4 w-4 shrink-0 items-center justify-center rounded-full bg-accent text-white">
                  <Check className="h-2.5 w-2.5" aria-hidden />
                </span>
              )}
            </button>
          );
        })}
      </div>

      {/* source input */}
      <Card className="mt-4 p-5">
        {tab === "file" ? (
          <>
            <input
              ref={fileRef}
              type="file"
              accept="video/*"
              multiple
              className="sr-only"
              aria-label="Choose video files"
              onChange={(e) => addFiles(e.target.files)}
            />
            <button
              type="button"
              onClick={() => fileRef.current?.click()}
              className="flex w-full flex-col items-center rounded-xl border border-dashed border-accent/45 bg-accent/[0.035] p-8 text-center transition-colors hover:border-accent/70"
            >
              <span className="flex h-11 w-11 items-center justify-center rounded-xl border border-accent/25 bg-accent/10">
                <UploadCloud className="h-5 w-5 text-accent" aria-hidden />
              </span>
              <span className="mt-3 text-[13.5px] font-semibold text-ink">
                Drag &amp; drop your video files here
              </span>
              <span className="mt-1 text-[11.5px] text-ink-3">
                or click to browse — select multiple files at once
              </span>
              <span className="mt-4 inline-flex h-9 items-center justify-center rounded-md bg-accent px-4 text-[12.5px] font-semibold text-white">
                <Upload className="mr-1.5 h-3.5 w-3.5" aria-hidden />
                Select videos
              </span>
            </button>
          </>
        ) : (
          <div className="space-y-3">
            <TextArea
              label={tab === "iframe" ? "Embed codes — one per line" : "Video URLs — one per line"}
              rows={4}
              placeholder={
                tab === "iframe"
                  ? `<iframe src="https://player.example.com/embed/abc"></iframe>\n<iframe src="https://player.example.com/embed/def"></iframe>`
                  : `https://cdn.example.com/scenes/one.mp4\nhttps://cdn.example.com/scenes/two.mp4`
              }
              value={bulkText}
              onChange={(e) => setBulkText(e.target.value)}
            />
            <div className="flex flex-wrap items-center gap-2">
              <Btn onClick={addBulkText}>
                <Upload className="h-3.5 w-3.5" aria-hidden />
                Add to queue
              </Btn>
              <span className="text-[11px] text-ink-3">
                {tab === "iframe"
                  ? "Every src attribute found becomes its own queue item."
                  : "Paste as many direct links as you like."}
              </span>
            </div>
          </div>
        )}

        <p className="mt-3 flex items-start gap-2 text-[11px] leading-relaxed text-ink-3">
          <TriangleAlert className="mt-0.5 h-3.5 w-3.5 shrink-0 text-amber-400" aria-hidden />
          Frontend demo — files stay in the browser, links are never fetched, and embeds are not
          loaded from their remote origin.
        </p>
        {error && <p className="mt-2 text-[11.5px] text-red-400">{error}</p>}
      </Card>

      {/* queue */}
      {queue.length > 0 && (
        <>
          <div className="mt-5 flex flex-wrap items-center gap-2">
            <h2 className="flex items-center gap-2 text-[14px] font-semibold tracking-tight text-ink">
              <ListChecks className="h-4 w-4 text-accent" aria-hidden />
              Upload queue
              <span className="text-[11.5px] font-medium text-ink-3">
                {readyCount}/{queue.length} ready
              </span>
            </h2>
            <div className="ml-auto flex flex-wrap items-center gap-2">
              <Select
                label="Apply category to all"
                value={applyCategory}
                onChange={(e) => {
                  const v = e.target.value;
                  setApplyCategory(v);
                  setQueue((q) => q.map((it) => ({ ...it, category: v })));
                }}
              >
                {categories.map((c) => (
                  <option key={c.id} value={c.label}>{c.label}</option>
                ))}
              </Select>
              <input
                value={applyTags}
                onChange={(e) => {
                  const v = e.target.value;
                  setApplyTags(v);
                  setQueue((q) => q.map((it) => ({ ...it, tags: v })));
                }}
                placeholder="Tags for all…"
                aria-label="Apply tags to all queued videos"
                className="h-8 w-[150px] rounded-md border border-line bg-void px-2.5 text-[12px] text-ink outline-none focus:border-accent/60"
              />
              <Btn variant="outline" size="sm" onClick={() => setQueue([])}>
                <Trash2 className="h-3.5 w-3.5" aria-hidden />
                Clear
              </Btn>
            </div>
          </div>

          <div className="mt-3 space-y-2.5">
            {queue.map((it, i) => {
              const SourceIcon =
                it.source === "file" ? FileVideo : it.source === "iframe" ? Code2 : Link2;
              return (
                <Card key={it.id} className="overflow-hidden">
                  {/* row */}
                  <div className="flex items-center gap-3 p-3">
                    <span className="w-4 shrink-0 text-center text-[11px] font-semibold tabular-nums text-ink-3">
                      {i + 1}
                    </span>

                    {/* thumbnail cell */}
                    <input
                      ref={(el) => { thumbRefs.current[it.id] = el; }}
                      type="file"
                      accept="image/*"
                      className="sr-only"
                      aria-label={`Thumbnail for ${it.title}`}
                      onChange={(e) => pickThumb(it.id, e.target.files?.[0])}
                    />
                    <button
                      type="button"
                      onClick={() => thumbRefs.current[it.id]?.click()}
                      className="group relative h-12 w-[84px] shrink-0 overflow-hidden rounded-md border border-line bg-pcard-2 transition-colors hover:border-accent/60"
                      aria-label={it.thumb ? "Replace thumbnail" : "Upload thumbnail"}
                    >
                      {it.thumb ? (
                        <>
                          <img src={it.thumb} alt="" className="h-full w-full object-cover" />
                          <span className="absolute inset-0 flex items-center justify-center bg-black/60 opacity-0 transition-opacity group-hover:opacity-100">
                            <ImagePlus className="h-4 w-4 text-white" aria-hidden />
                          </span>
                        </>
                      ) : (
                        <span className="flex h-full flex-col items-center justify-center gap-0.5 text-ink-3">
                          <ImagePlus className="h-3.5 w-3.5 text-accent" aria-hidden />
                          <span className="text-[8.5px] font-medium">16:9</span>
                        </span>
                      )}
                    </button>

                    {/* title + source */}
                    <div className="min-w-0 flex-1">
                      <input
                        value={it.title}
                        onChange={(e) => patch(it.id, { title: e.target.value })}
                        placeholder="Untitled video"
                        aria-label={`Title for item ${i + 1}`}
                        className="w-full truncate rounded-md border border-transparent bg-transparent px-1.5 py-1 text-[13px] font-medium text-ink outline-none transition-colors hover:border-line focus:border-accent/60 focus:bg-void"
                      />
                      <p className="mt-0.5 flex items-center gap-1.5 truncate px-1.5 text-[10.5px] text-ink-3">
                        <SourceIcon className="h-3 w-3 shrink-0" aria-hidden />
                        <span className="truncate">{it.sourceLabel}</span>
                      </p>
                    </div>

                    {/* auto-detected metadata */}
                    {it.phase === "ready" ? (
                      <div className="hidden shrink-0 items-center gap-1.5 sm:flex">
                        <span
                          title="Detected automatically"
                          className="flex items-center gap-1 rounded-full border border-line bg-pcard-2 px-2 py-0.5 text-[10px] font-semibold tabular-nums text-ink-2"
                        >
                          <Sparkles className="h-2.5 w-2.5 text-accent" aria-hidden />
                          {it.duration}
                        </span>
                        <span className="rounded-full border border-line bg-pcard-2 px-2 py-0.5 text-[10px] font-semibold text-ink-2">
                          {it.quality}
                        </span>
                      </div>
                    ) : (
                      <span className="flex shrink-0 items-center gap-1.5 text-[10.5px] text-ink-3">
                        <Loader2 className="h-3 w-3 animate-spin text-accent" aria-hidden />
                        {it.phase === "uploading" ? `${it.progress}%` : "Analysing…"}
                      </span>
                    )}

                    <button
                      type="button"
                      onClick={() => patch(it.id, { expanded: !it.expanded })}
                      aria-expanded={it.expanded}
                      aria-label="Toggle details"
                      className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md border border-line text-ink-3 transition-colors hover:border-zinc-500 hover:text-ink"
                    >
                      <ChevronDown
                        className={cn("h-3.5 w-3.5 transition-transform", it.expanded && "rotate-180")}
                        aria-hidden
                      />
                    </button>
                    <button
                      type="button"
                      onClick={() => setQueue((q) => q.filter((x) => x.id !== it.id))}
                      aria-label={`Remove ${it.title}`}
                      className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md border border-line text-ink-3 transition-colors hover:border-red-500/50 hover:text-red-400"
                    >
                      <X className="h-3.5 w-3.5" aria-hidden />
                    </button>
                  </div>

                  {/* progress */}
                  {it.phase !== "ready" && (
                    <div className="h-1 w-full bg-void">
                      <div
                        className="h-full bg-accent transition-all duration-150"
                        style={{ width: `${it.progress}%` }}
                      />
                    </div>
                  )}

                  {/* per-item details */}
                  {it.expanded && (
                    <div className="border-t border-line bg-pcard-2/60 p-4">
                      <div className="grid gap-3.5 lg:grid-cols-[1fr_1fr]">
                        <TextArea
                          label="Description"
                          rows={3}
                          placeholder="Short editorial summary shown on the watch page…"
                          value={it.description}
                          onChange={(e) => patch(it.id, { description: e.target.value })}
                        />
                        <div className="space-y-3.5">
                          <div className="grid grid-cols-2 gap-3">
                            <label className="block">
                              <span className="mb-1.5 block text-[11.5px] font-medium text-ink-2">
                                Category
                              </span>
                              <Select
                                label="Category"
                                className="w-full [&>select]:h-9 [&>select]:w-full [&>select]:text-[12.5px]"
                                value={it.category}
                                onChange={(e) => patch(it.id, { category: e.target.value })}
                              >
                                {categories.map((c) => (
                                  <option key={c.id} value={c.label}>{c.label}</option>
                                ))}
                              </Select>
                            </label>
                            <Field
                              label="Tags"
                              placeholder="featured, 4k"
                              value={it.tags}
                              onChange={(e) => patch(it.id, { tags: e.target.value })}
                            />
                          </div>

                          {/* auto-generated, read-only */}
                          <div className="rounded-lg border border-line bg-pcard p-3">
                            <p className="flex items-center gap-1.5 text-[10.5px] font-semibold uppercase tracking-wider text-ink-3">
                              <Sparkles className="h-3 w-3 text-accent" aria-hidden />
                              Detected automatically
                            </p>
                            <div className="mt-2 grid grid-cols-3 gap-2 text-center">
                              {[
                                { label: "Duration", value: it.duration },
                                { label: "Quality", value: it.quality },
                                { label: "Ratio", value: "16:9" },
                              ].map((m) => (
                                <div key={m.label} className="rounded-md border border-line bg-pcard-2 py-1.5">
                                  <p className="text-[12.5px] font-semibold tabular-nums text-ink">
                                    {m.value}
                                  </p>
                                  <p className="text-[9px] uppercase tracking-wider text-ink-3">
                                    {m.label}
                                  </p>
                                </div>
                              ))}
                            </div>
                          </div>

                          <div className="flex items-center justify-between rounded-lg border border-line bg-pcard px-3 py-2">
                            <span className="truncate text-[11px] text-ink-3">{it.thumbName}</span>
                            <button
                              type="button"
                              onClick={() => thumbRefs.current[it.id]?.click()}
                              className="shrink-0 text-[11px] font-semibold text-accent hover:text-accent-soft"
                            >
                              {it.thumb ? "Replace thumbnail" : "Upload thumbnail"}
                            </button>
                          </div>
                        </div>
                      </div>
                    </div>
                  )}
                </Card>
              );
            })}
          </div>

          {/* actions */}
          <div className="mt-5 flex flex-wrap items-center justify-end gap-2.5 border-t border-line pt-4">
            <span className="mr-auto text-[11px] text-ink-3">
              {allReady
                ? `${queue.length} video${queue.length === 1 ? "" : "s"} ready — nothing is uploaded in this demo.`
                : "Processing… actions unlock when every item is ready."}
            </span>
            <Btn variant="outline" disabled={!allReady} onClick={() => submit(false)}>
              Save all as drafts
            </Btn>
            <Btn disabled={!allReady} onClick={() => submit(true)}>
              <Upload className="h-3.5 w-3.5" aria-hidden />
              Publish {queue.length} video{queue.length === 1 ? "" : "s"}
            </Btn>
          </div>
        </>
      )}
    </div>
  );
}
