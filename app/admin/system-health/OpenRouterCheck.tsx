"use client";

import { useState } from "react";
import { AlertTriangle, CheckCircle2, LoaderCircle, PlugZap } from "lucide-react";
import {
  OPENROUTER_MODEL,
  openRouterDiagnostics,
  probeOpenRouter,
  type OpenRouterProbeResult,
} from "@/lib/openrouter/browser-client";

/**
 * Admin-side OpenRouter connectivity test.
 *
 * The probe runs **directly in the browser** against
 * https://openrouter.ai/api/v1/chat/completions — there is no backend proxy
 * and no server endpoint involved. The API key is read from the public
 * NEXT_PUBLIC_OPENROUTER_API_KEY build variable: it is compiled into browser
 * code by design, so it is never displayed, logged, or treated as a secret
 * here (extracting it is trivially possible for any visitor — restricting the
 * UI to administrators does not prevent that).
 *
 * The panel never claims the provider is verified because a key exists:
 * "key present" only means the variable is set; only the live probe reports
 * what actually happened.
 */
export default function OpenRouterCheck() {
  const diagnostics = openRouterDiagnostics();
  const [probe, setProbe] = useState<OpenRouterProbeResult | null>(null);
  const [probing, setProbing] = useState(false);
  const [error, setError] = useState("");

  async function runProbe() {
    setProbing(true);
    setProbe(null);
    setError("");
    try {
      const result = await probeOpenRouter();
      setProbe(result);
    } catch (probeError: unknown) {
      setError(probeError instanceof Error ? probeError.message : "OpenRouter connectivity test failed");
    } finally {
      setProbing(false);
    }
  }

  const statusLine = diagnostics.configured
    ? "Key present in this build — not yet verified"
    : "No key in this build";

  return (
    <div className="mt-6 rounded-lg border border-line bg-pcard p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <p className="text-[13px] font-semibold">OpenRouter — metadata suggestions</p>
          <p className="mt-1 text-[11px] text-ink-3">
            Title, description, and tags for new videos, generated directly from this browser through OpenRouter — no
            backend proxy. The configured model is{" "}
            <code className="font-mono text-ink-2">{OPENROUTER_MODEL}</code>.
          </p>
        </div>
        <button
          type="button"
          onClick={runProbe}
          disabled={probing}
          className="inline-flex h-8 items-center gap-1.5 rounded-md border border-line px-3 text-[11px] hover:bg-white/5 disabled:opacity-50"
        >
          {probing ? (
            <LoaderCircle aria-hidden="true" className="h-3.5 w-3.5 animate-spin" />
          ) : (
            <PlugZap aria-hidden="true" className="h-3.5 w-3.5" />
          )}
          Test OpenRouter
        </button>
      </div>

      <p className="mt-3 text-[11px] text-ink-3">
        Provider <span className="font-mono text-ink-2">openrouter.ai</span> · model{" "}
        <span className="font-mono text-ink-2">{diagnostics.model}</span> · key{" "}
        <span className="text-ink-2">{statusLine}</span>
        {!diagnostics.configured ? (
          <>
            {" "}
            — set <code className="font-mono">NEXT_PUBLIC_OPENROUTER_API_KEY</code> and rebuild to enable AI metadata.
          </>
        ) : null}
      </p>

      {probe && (
        <p
          className={`mt-3 flex items-start gap-2 rounded-md p-3 text-[11.5px] ${
            probe.ok ? "bg-emerald-500/10 text-emerald-200" : "bg-amber-500/10 text-amber-200"
          }`}
          role="status"
          aria-live="polite"
        >
          {probe.ok ? (
            <CheckCircle2 aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          ) : (
            <AlertTriangle aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          )}
          <span>
            {probe.ok
              ? `OpenRouter answered with ${probe.model} in ${probe.latencyMs} ms — live connectivity confirmed; metadata suggestions will be generated by AI.`
              : `OpenRouter test failed${probe.latencyMs ? ` after ${probe.latencyMs} ms` : ""}: ${probe.error || "no response"}`}
            {!probe.ok && probe.hint ? <span className="mt-1 block text-amber-100/90">{probe.hint}</span> : null}
          </span>
        </p>
      )}

      {error && (
        <p className="mt-3 flex items-start gap-2 rounded-md bg-amber-500/10 p-3 text-[11.5px] text-amber-200" role="alert">
          <AlertTriangle aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          {error}
        </p>
      )}

      <p className="mt-3 text-[11px] text-ink-3">
        The test spends a few tokens of the OpenRouter account&apos;s real credit and calls the provider directly from
        your browser. The API key is public by design (it is compiled into the frontend bundle) — it is never displayed
        or logged here. Until a test succeeds, this provider is reported as untested, not operational.
      </p>
    </div>
  );
}
