"use client";

import { useCallback, useEffect, useState } from "react";
import { AlertTriangle, CheckCircle2, LoaderCircle, RefreshCw, Sparkles } from "lucide-react";
import { readApiResponse } from "@/src/utils/api";

type RouteHealth = {
  model: string;
  benched: boolean;
  stalls: number;
  cooldownRemainingMs: number;
};

type Diagnostics = {
  configured: boolean;
  keyKind: "openrouter" | "unknown" | "missing";
  provider: string;
  endpoint: string;
  model: string;
  defaultModel: string;
  /** Routes a draft request may ask, preferred first (fallbacks included). */
  models: string[];
  /** Routes benched in this process because they stopped answering. */
  routeHealth: RouteHealth[];
  routeTimeoutMs: number;
  reasoning: string;
  maxOutputTokens: number;
};

type Probe = {
  ok: boolean;
  configured: boolean;
  keyKind: Diagnostics["keyKind"];
  model: string;
  latencyMs: number;
  error?: string;
  hint?: string;
};

const KEY_KIND_LABEL: Record<Diagnostics["keyKind"], string> = {
  openrouter: "sk-or- OpenRouter key",
  unknown: "key set (unrecognised format)",
  missing: "no key",
};

export default function OpenRouterCheck() {
  const [diagnostics, setDiagnostics] = useState<Diagnostics | null>(null);
  const [probe, setProbe] = useState<Probe | null>(null);
  const [loading, setLoading] = useState(true);
  const [probing, setProbing] = useState(false);
  const [error, setError] = useState("");

  const load = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      const response = await fetch("/api/admin/metadata/health", { cache: "no-store" });
      setDiagnostics(await readApiResponse<Diagnostics>(response));
    } catch (loadError: unknown) {
      setError(loadError instanceof Error ? loadError.message : "Could not read the OpenRouter configuration");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  async function runProbe() {
    setProbing(true);
    setProbe(null);
    setError("");
    try {
      const response = await fetch("/api/admin/metadata/health", { method: "POST" });
      const json = await readApiResponse<{ probe: Probe }>(response);
      setProbe(json.probe);
    } catch (probeError: unknown) {
      const message = probeError instanceof Error ? probeError.message : "OpenRouter probe failed";
      setProbe({ ok: false, configured: Boolean(diagnostics?.configured), keyKind: diagnostics?.keyKind || "missing", model: diagnostics?.model || "—", latencyMs: 0, error: message });
    } finally {
      setProbing(false);
    }
  }

  return (
    <div className="mt-6 rounded-lg border border-line bg-pcard p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <p className="text-[13px] font-semibold">OpenRouter — metadata suggestions</p>
          <p className="mt-1 text-[11px] text-ink-3">
            Title, description, and tags for new videos, generated by NVIDIA
            Nemotron 3 Ultra (free) through OpenRouter, with free fallback routes
            for when that endpoint stops answering. Reasoning is disabled for
            speed; every suggestion still needs human review.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={runProbe}
            disabled={probing || loading || !diagnostics?.configured}
            className="inline-flex h-8 items-center gap-1.5 rounded-md border border-line px-3 text-[11px] hover:bg-white/5 disabled:opacity-50"
          >
            {probing ? <LoaderCircle aria-hidden="true" className="h-3.5 w-3.5 animate-spin" /> : <Sparkles aria-hidden="true" className="h-3.5 w-3.5" />}
            Test OpenRouter
          </button>
          <button
            type="button"
            onClick={load}
            disabled={loading}
            className="inline-flex h-8 items-center gap-1.5 rounded-md border border-line px-3 text-[11px] hover:bg-white/5 disabled:opacity-50"
          >
            {loading ? <LoaderCircle aria-hidden="true" className="h-3.5 w-3.5 animate-spin" /> : <RefreshCw aria-hidden="true" className="h-3.5 w-3.5" />}
            Re-check setup
          </button>
        </div>
      </div>

      {diagnostics && (
        <p className="mt-3 text-[11px] text-ink-3">
          Key: <span className="text-ink-2">{KEY_KIND_LABEL[diagnostics.keyKind]}</span> · endpoint{" "}
          <span className="font-mono text-ink-2">{diagnostics.endpoint}</span> · model{" "}
          <span className="font-mono text-ink-2">{diagnostics.model}</span> · reasoning{" "}
          <span className="text-ink-2">{diagnostics.reasoning}</span> · output budget{" "}
          <span className="tabular-nums text-ink-2">{diagnostics.maxOutputTokens}</span> tokens
          {diagnostics.models.length > 1 ? (
            <>
              {" "}
              · routes{" "}
              <span className="font-mono text-ink-2">{diagnostics.models.join(" → ")}</span> (each gets{" "}
              <span className="tabular-nums text-ink-2">
                {Math.round(diagnostics.routeTimeoutMs / 1000)}
              </span>{" "}
              s before the next one is asked)
            </>
          ) : null}
        </p>
      )}

      {diagnostics?.routeHealth.some((route) => route.benched) ? (
        <p className="mt-2 text-[11px] text-amber-200">
          Skipping{" "}
          <span className="font-mono">
            {diagnostics.routeHealth
              .filter((route) => route.benched)
              .map((route) => route.model)
              .join(", ")}
          </span>{" "}
          for up to{" "}
          <span className="tabular-nums">
            {Math.ceil(
              Math.max(
                ...diagnostics.routeHealth
                  .filter((route) => route.benched)
                  .map((route) => route.cooldownRemainingMs),
              ) / 1000,
            )}
          </span>{" "}
          s: those routes stopped answering inside their share of a request. Titles keep coming from
          the remaining routes in the meantime, and the skipped route is retried automatically.
        </p>
      ) : null}

      {probe && (
        <p
          className={`mt-3 flex items-start gap-2 rounded-md p-3 text-[11.5px] ${
            probe.ok ? "bg-emerald-500/10 text-emerald-200" : "bg-amber-500/10 text-amber-200"
          }`}
        >
          {probe.ok ? (
            <CheckCircle2 aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          ) : (
            <AlertTriangle aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          )}
          <span>
            {probe.ok
              ? `OpenRouter answered with ${probe.model} in ${probe.latencyMs} ms — metadata suggestions will be generated by AI.`
              : `OpenRouter probe failed with ${probe.model}${probe.latencyMs ? ` after ${probe.latencyMs} ms` : ""}: ${probe.error || "no response"}`}
            {!probe.ok && probe.hint ? <span className="mt-1 block text-amber-100/90">{probe.hint}</span> : null}
          </span>
        </p>
      )}

      {error && (
        <p className="mt-3 flex items-start gap-2 rounded-md bg-amber-500/10 p-3 text-[11.5px] text-amber-200">
          <AlertTriangle aria-hidden="true" className="mt-0.5 h-3.5 w-3.5 shrink-0" />
          {error}
        </p>
      )}

      <p className="mt-3 text-[11px] text-ink-3">
        The probe uses a 32-token completion cap and counts as an OpenRouter request. Key values are never displayed —
        only whether a key is present and which format it uses.
      </p>
    </div>
  );
}
